export function localizeMessage(message, locale) {
  if (locale !== "en" || typeof message !== "string") return message;
  if (ENGLISH_MESSAGES.has(message)) return ENGLISH_MESSAGES.get(message);
  if (/^(active|archived|deleted|bookmarked|reacted) 必須是布林值。$/.test(message)) {
    return message.replace(" 必須是布林值。", " must be a boolean.");
  }
  if (message === "sortOrder 必須是整數。") return "sortOrder must be an integer.";
  if (message === "messages 必須是陣列。") return "messages must be an array.";
  if (message === "state 只能是 active、deleted 或 all。") return "state must be active, deleted, or all.";
  if (message.startsWith("附件不可超過 ")) return message.replace("附件不可超過 ", "Attachments cannot exceed ");
  return message;
}
